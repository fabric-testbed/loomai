def gen_readme(name: str, description: str, experiment: str, realization: str,
               nodes: list[dict], links: list[dict], scripts: list[dict]) -> str:
    topo = "\n".join(
        f"- **{n.get('name')}**" + (f" — facility `{n.get('facility')}`" if n.get('facility') else "")
        for n in nodes)
    link_lines = "\n".join(
        "- " + " ↔ ".join(l.get("members") or []) for l in links) or "- (none)"
    script_lines = "\n".join(
        f"- `scripts/{s.get('name')}` → `{s.get('target') or 'all'}`" for s in scripts) or "- (none)"
    return f"""# {name}

{description or "A reproducible SPHERE experiment packaged as a LoomAI weave."}

## Topology
**Experiment:** `{experiment}`  **Realization:** `{realization}`

### Nodes
{topo}

### Links
{link_lines}

### Setup scripts
{script_lines}

## Recreate it
1. **Run** this weave from the LoomAI Libraries panel (or `loomai weaves run`).
   It will recreate the experiment, push `model.py`, realize, and materialize.
2. Attach an XDC to the realization (Editor → XDC), then **Notebook → Send weave
   → XDC** and **Open JupyterLab**, and run `analysis.ipynb`.
3. Click **Stop** to dematerialize and relinquish the realization.

> The mergexp source in `model.py` was regenerated from the compiled topology.
"""


def package_experiment(
    *,
    artifacts_dir: str,
    name: str,
    description: str,
    experiment: str,
    realization: str,
    project: str | None,
    topology: dict,
    scripts: list[dict] | None = None,
    include_notebook: bool = True,
    tags: list[str] | None = None,
    dir_name: str | None = None,
    description_short: str = "",
    description_long: str = "",
) -> dict[str, Any]:
    """Write a complete SPHERE weave to ``artifacts_dir/<safe_name>/``.

    ``name`` is the human **title** (shown in Libraries / the publish dialog);
    ``dir_name`` is the stable on-disk identifier (defaults to a sanitized
    ``name``). ``description`` / ``description_short`` (<=255) / ``description_long``
    (HTML) feed the publish metadata. ``topology`` is a ``{network?, nodes, links}``
    result; ``scripts`` is ``[{name, content, target}]``.
    Returns ``{dir_name, path, files}``.
    """
    scripts = scripts or []
    nodes = topology.get("nodes") or []
    links = topology.get("links") or []
    network = topology.get("network") or experiment

    # Validate + sanitize bundled script filenames (no path traversal).
    clean_scripts: list[dict] = []
    for s in scripts:
        fn = (s.get("name") or "").strip()
        if not fn or not _SCRIPT_NAME_RE.match(fn) or fn.startswith("."):
            raise ValueError(f"invalid script filename: {fn!r}")
        clean_scripts.append({"name": fn, "content": s.get("content") or "",
                              "target": (s.get("target") or "all").strip() or "all"})

    # On-disk dir name is a stable identifier, separate from the display title.
    safe = re.sub(r"[^A-Za-z0-9_\-]", "_", (dir_name or name or experiment).strip())
    if not safe:
        raise ValueError("invalid weave name")
    base = os.path.realpath(artifacts_dir)
    dest = os.path.realpath(os.path.join(base, safe))
    if not dest.startswith(base + os.sep) and dest != base:
        raise ValueError("invalid weave name")
    os.makedirs(dest, exist_ok=True)

    model_src = gen_mergexp(network, nodes, links)
    files: list[str] = []

    def _write(rel: str, content: str):
        path = os.path.join(dest, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write(content)
        files.append(rel)

    _write("model.py", model_src)
    _write("experiment.py", gen_experiment_py())
    _write("weave.sh", gen_weave_sh(experiment))
    os.chmod(os.path.join(dest, "weave.sh"), 0o755)
    os.chmod(os.path.join(dest, "experiment.py"), 0o755)
    _write(".weaveignore", _WEAVEIGNORE)
    _write("README.md", gen_readme(name, description, experiment, realization,
                                   nodes, links, clean_scripts))
    for s in clean_scripts:
        _write(os.path.join("scripts", s["name"]), s["content"])
    if include_notebook:
        _write("analysis.ipynb",
               json.dumps(gen_notebook(name, description, experiment, realization,
                                       project or "", nodes, links, clean_scripts),
                          indent=1))

    _default_desc = f"SPHERE experiment '{experiment}' packaged as a reproducible weave."
    short = (description_short or description or _default_desc).strip()[:255]
    weave_json = {
        "name": name or experiment,                 # human title (publish dialog default)
        "title": name or experiment,
        "description": short,                       # short blurb (<=255, publish "short")
        "description_short": short,
        "description_long": description_long or "",  # HTML (publish "long")
        "run_script": "weave.sh",
        "log_file": "weave.log",
        "format": "sphere-experiment-v1",
        "created": datetime.now(timezone.utc).isoformat(),
        # The FABRIC Artifact Manager only accepts tags from a controlled vocabulary.
        "tags": tags or ["loomai:weave", "experiment pattern"],
        "args": [
            {"name": "EXPERIMENT_NAME", "label": "Experiment Name", "type": "string",
             "required": True, "default": experiment,
             "description": "SPHERE experiment name to (re)create"},
            {"name": "REALIZATION_ID", "label": "Realization ID", "type": "string",
             "required": True, "default": realization,
             "description": "Realization id to embed and materialize"},
        ],
        "sphere": {
            "experiment": experiment,
            "realization": realization,
            "project": project,
            "network": network,
            "model": "model.py",
            "nodes": nodes,
            "links": links,
            "scripts": [{"name": s["name"], "target": s["target"]} for s in clean_scripts],
            "notebook": "analysis.ipynb" if include_notebook else None,
        },
    }
    _write("weave.json", json.dumps(weave_json, indent=2))

    return {"dir_name": safe, "path": dest, "files": sorted(files),
            "format": "sphere-experiment-v1"}
