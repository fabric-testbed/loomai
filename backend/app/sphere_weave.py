"""Package a live SPHERE experiment into a reproducible LoomAI weave.

A SPHERE weave is an ordinary ``my_artifacts/<dir>/`` artifact (so it shows up in
the Libraries panel and can be published to the FABRIC Artifact Manager) with
``format: "sphere-experiment-v1"``. It bundles everything needed to recreate the
experiment from scratch:

  weave.json        metadata + the reconstructed topology + a ``sphere`` block
  model.py          the mergexp model, regenerated from the compiled topology
  experiment.py     lifecycle driver (create -> push -> realize -> materialize)
  weave.sh          the Run/Stop orchestrator (start/monitor/stop)
  scripts/*.sh      per-node setup scripts the author bundled
  analysis.ipynb    starter notebook (SSH to nodes via the XDC, run + analyze)
  README.md         human-readable recreate instructions
  .weaveignore      publish exclusions

The mergexp *source* is not stored by the portal, so it is regenerated from the
compiled model topology (the same shape the builder uses) — see ``gen_mergexp``.
"""

from __future__ import annotations

import json
import os
import re
from datetime import datetime, timezone
from typing import Any

_IDENT_RE = re.compile(r"^[A-Za-z_][A-Za-z0-9_]*$")
_SCRIPT_NAME_RE = re.compile(r"^[A-Za-z0-9._-]+$")


def _py_str(value: str) -> str:
    """Single-quote a value for safe embedding in generated Python source."""
    return "'" + str(value).replace("\\", "\\\\").replace("'", "\\'") + "'"


# --------------------------------------------------------------------------- #
# mergexp source regeneration (mirrors the frontend builder's genMergexp)
# --------------------------------------------------------------------------- #
def gen_mergexp(network: str, nodes: list[dict], links: list[dict]) -> str:
    """Reconstruct mergexp model source from a compiled topology.

    ``nodes``: ``[{name, facility?}]``; ``links``: ``[{members:[..], addrs:{name:cidr}}]``.
    Node names must be valid Python identifiers (mergexp ids always are).
    """
    net = network or "experiment"
    lines = ["from mergexp import *", "", f"net = Network({_py_str(net)})", ""]
    for n in nodes:
        name = n.get("name") or ""
        if not _IDENT_RE.match(name):
            raise ValueError(f"node name is not a valid identifier: {name!r}")
        fac = (n.get("facility") or "").strip()
        if fac:
            lines.append(f"{name} = net.node({_py_str(name)}, facility == {_py_str(fac)})")
        else:
            lines.append(f"{name} = net.node({_py_str(name)})")
    lines.append("")
    for i, link in enumerate(links):
        members = [m for m in (link.get("members") or []) if _IDENT_RE.match(m or "")]
        if len(members) < 2:
            continue
        var = f"link{i}"
        lines.append(f"{var} = net.connect([{', '.join(members)}])")
        addrs = link.get("addrs") or {}
        for m in members:
            cidr = (addrs.get(m) or "").strip()
            if cidr:
                lines.append(f"{var}[{m}].socket.addrs = ip4({_py_str(cidr)})")
    lines.append("")
    lines.append("experiment(net)")
    return "\n".join(lines) + "\n"


# --------------------------------------------------------------------------- #
# Lifecycle driver — recreates the experiment by calling the local backend API
# --------------------------------------------------------------------------- #
_EXPERIMENT_PY = r'''#!/usr/bin/env python3
"""SPHERE weave lifecycle driver (auto-generated by LoomAI).

Drives the experiment through the local LoomAI backend's SPHERE API so it reuses
the running portal session/auth. Invoked by weave.sh as:

    experiment.py start   <experiment_name>
    experiment.py monitor <experiment_name>
    experiment.py stop    <experiment_name>
"""
import json, os, sys, time, urllib.request, urllib.error

BASE = os.environ.get("LOOMAI_API", "http://127.0.0.1:8000")
HERE = os.path.dirname(os.path.abspath(__file__))
CFG = json.load(open(os.path.join(HERE, "weave.json")))
SPH = CFG.get("sphere", {})
PROJECT = os.environ.get("SPHERE_PROJECT") or SPH.get("project") or None
RID = os.environ.get("REALIZATION_ID") or SPH.get("realization") or "r0"
MODEL_FILE = SPH.get("model", "model.py")
TAG = "weave"


def _api(method, path, body=None):
    url = BASE + path
    data = json.dumps(body).encode() if body is not None else None
    req = urllib.request.Request(url, data=data, method=method,
                                 headers={"Content-Type": "application/json"})
    try:
        with urllib.request.urlopen(req, timeout=120) as r:
            raw = r.read().decode()
            return json.loads(raw) if raw else {}
    except urllib.error.HTTPError as e:
        detail = e.read().decode()[:400]
        raise SystemExit(f"### ERROR: {method} {path} -> {e.code}: {detail}")


def _p(b):  # attach project to a body when configured
    return {**b, "project": PROJECT} if PROJECT else b


def start(exp):
    print(f"### PROGRESS: Recreating SPHERE experiment '{exp}' (realization '{RID}')")
    model = open(os.path.join(HERE, MODEL_FILE)).read()

    # 1. experiment (idempotent — ignore "already exists")
    try:
        _api("POST", "/api/sphere/experiments", _p({"experiment": exp,
             "description": CFG.get("description", "")}))
        print(f"### PROGRESS: created experiment {exp}")
    except SystemExit as e:
        print(f"### PROGRESS: experiment exists or create skipped ({e})")

    # 2. push model
    _api("POST", "/api/sphere/models", _p({"model": model, "experiment": exp, "tag": TAG}))
    print("### PROGRESS: pushed model")

    # 3. realize (poll to completion)
    _api("POST", "/api/sphere/realizations", _p({"experiment": exp, "realization": RID, "tag": TAG}))
    print("### PROGRESS: realize requested; embedding...")
    for _ in range(40):
        time.sleep(3)
        rs = _api("GET", f"/api/sphere/realizations?state=true"
                  + (f"&project={PROJECT}" if PROJECT else ""))
        cur = next((r for r in rs if r.get("eid") == exp and r.get("id") == RID), None)
        st = (cur or {}).get("state")
        if st == "complete":
            print("### PROGRESS: realization complete"); break
        if st == "failed":
            raise SystemExit(f"### ERROR: realization failed: {(cur or {}).get('error', '')}")
    else:
        raise SystemExit("### ERROR: realization did not complete in time")

    # 4. materialize (poll to Success)
    _api("POST", "/api/sphere/materializations", _p({"experiment": exp, "realization": RID}))
    print("### PROGRESS: materialize requested...")
    for _ in range(60):
        time.sleep(4)
        m = _api("GET", f"/api/sphere/materializations/{exp}/{RID}"
                 + (f"?project={PROJECT}" if PROJECT else ""))
        hs = (m.get("taskSummary") or {}).get("HighestStatus")
        if hs == "Success":
            print("### PROGRESS: materialization Success — experiment is up."); return
        if hs in ("Error", "Failure"):
            raise SystemExit(f"### ERROR: materialization {hs}")
    raise SystemExit("### ERROR: materialization did not finish in time")


def monitor(exp):
    rs = _api("GET", "/api/sphere/realizations?state=true"
              + (f"&project={PROJECT}" if PROJECT else ""))
    cur = next((r for r in rs if r.get("eid") == exp and r.get("id") == RID), None)
    if not cur:
        print("### ERROR: realization no longer present"); return 1
    if cur.get("state") == "failed":
        print(f"### ERROR: realization failed: {cur.get('error', '')}"); return 1
    print(f"### PROGRESS: {exp}/{RID} state={cur.get('state')}")
    return 0


def stop(exp):
    print(f"### PROGRESS: Tearing down {exp}/{RID}")
    q = f"?project={PROJECT}" if PROJECT else ""
    try:
        _api("DELETE", f"/api/sphere/materializations/{exp}/{RID}{q}")
        print("### PROGRESS: dematerialized")
    except SystemExit as e:
        print(f"### PROGRESS: dematerialize skipped ({e})")
    try:
        _api("DELETE", f"/api/sphere/realizations/{exp}/{RID}{q}")
        print("### PROGRESS: relinquished")
    except SystemExit as e:
        print(f"### PROGRESS: relinquish skipped ({e})")


if __name__ == "__main__":
    if len(sys.argv) < 3:
        print("usage: experiment.py {start|monitor|stop} <experiment>"); sys.exit(2)
    cmd, exp = sys.argv[1], sys.argv[2]
    fn = {"start": start, "monitor": monitor, "stop": stop}.get(cmd)
    if not fn:
        print(f"unknown command: {cmd}"); sys.exit(2)
    sys.exit(fn(exp) or 0)
'''


def gen_experiment_py() -> str:
    return _EXPERIMENT_PY


def gen_weave_sh(default_experiment: str) -> str:
    safe_default = default_experiment if re.match(r"^[a-z][a-z0-9]{0,62}$", default_experiment) else "experiment"
    return f'''#!/bin/bash
#
# SPHERE experiment weave — Run/Stop orchestrator (auto-generated by LoomAI).
#
EXPERIMENT_NAME="${{EXPERIMENT_NAME:-${{1:-{safe_default}}}}}"
EXPERIMENT_NAME=$(echo "$EXPERIMENT_NAME" | tr 'A-Z' 'a-z' | sed 's/[^a-z0-9]//g')
if [ -z "$EXPERIMENT_NAME" ]; then
  echo "ERROR: EXPERIMENT_NAME not set" >&2
  exit 1
fi
SCRIPT="$(dirname "$0")/experiment.py"

cleanup() {{
  echo ""
  echo "### PROGRESS: Stop requested — tearing down..."
  python3 "$SCRIPT" stop "$EXPERIMENT_NAME" 2>&1 || true
  echo "### PROGRESS: Done."
  exit 0
}}
trap cleanup SIGTERM SIGINT

if ! python3 "$SCRIPT" start "$EXPERIMENT_NAME"; then
  echo "ERROR: Failed to bring up experiment"
  exit 1
fi

echo "### PROGRESS: Up. Monitoring (click Stop to tear down)..."
while true; do
  if ! python3 "$SCRIPT" monitor "$EXPERIMENT_NAME"; then
    echo "ERROR: Monitor detected a problem"
    exit 1
  fi
  sleep 60 &
  wait $! 2>/dev/null || true
done
'''


